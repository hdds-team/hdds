"""Render the ROS 2 distro status table from the gate's own result JSON.

docs/ros2/index.md has claimed "Full support" for Humble, Iron and Jazzy since
before any gate built the package. This renders the table from measurements
instead, and REFUSES to print "Full support" unless the run was BOTH complete
and green: every case in the gate's own expected set was executed, and none of
them failed. A subset run - `--cases reader_first`, say - used to render
"Full support | 1/1 gate cases" for a distro whose other cases were never run,
which is the same false claim in a smaller font.

Usage: render-status.py <evidence-dir> [--format md|json]
  <evidence-dir> holds <distro>/result.json as gate-ros2-pubsub.sh writes it.
"""
from __future__ import annotations

import json
import os
import sys

DISTROS = ("humble", "iron", "jazzy")

# The label each distro gets when every case passes. Iron is end of life
# upstream (last osrf image 2025-06-08); it is built and gated all the same,
# and only the label differs.
FULL_LABEL = {
    "humble": "Full support",
    "iron": "Builds and passes the gate; unmaintained upstream (EOL)",
    "jazzy": "Full support",
}


def load(evidence_dir: str, distro: str) -> dict | None:
    path = os.path.join(evidence_dir, distro, "result.json")
    if not os.path.exists(path):
        return None
    with open(path) as handle:
        return json.load(handle)


def status_for(result: dict | None, distro: str) -> tuple[str, str]:
    if result is None:
        return "Not measured", "no result.json in the evidence directory"
    cases = result.get("cases", [])
    failed = [c["name"] for c in cases if c.get("verdict") == "FAIL"]
    passed = [c["name"] for c in cases if c.get("verdict") == "PASS"]
    if not cases:
        return "Not measured", "the gate produced no case"
    if failed:
        return (
            f"Partial: {len(passed)}/{len(cases)} gate cases",
            "red: " + ", ".join(failed),
        )

    # Green, but is it COMPLETE? cases_expected is the gate's own full case
    # list; without it (a result.json older than this field) we cannot tell a
    # sweep from a subset, so we do not claim one.
    expected = result.get("cases_expected")
    if not expected:
        return (
            f"Partial: {len(passed)} gate cases, coverage unknown",
            "this result.json predates cases_expected: rerun the gate",
        )
    executed = {c["name"] for c in cases}
    # `graph` records two case names; a distro that ran it has both.
    missing = [name for name in expected if name not in executed and name != "graph"]
    if "graph" in expected and not ({"graph_topics", "graph_nodes"} & executed):
        missing.append("graph")
    if missing:
        return (
            f"Partial: {len(passed)}/{len(cases)} of a {len(expected)}-case gate (subset run)",
            "never run: " + ", ".join(missing),
        )
    return FULL_LABEL.get(distro, "Full support"), f"{len(passed)}/{len(cases)} gate cases"


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    evidence_dir = sys.argv[1]
    fmt = "md"
    if "--format" in sys.argv:
        fmt = sys.argv[sys.argv.index("--format") + 1]

    rows = []
    sha = "unknown"
    date = "unknown"
    for distro in DISTROS:
        result = load(evidence_dir, distro)
        if result:
            sha = result.get("tree_sha", sha)
            date = result.get("date_utc", date)
        label, detail = status_for(result, distro)
        rows.append({"distro": distro, "status": label, "detail": detail})

    if fmt == "json":
        json.dump({"tree_sha": sha, "date_utc": date, "rows": rows}, sys.stdout, indent=2)
        sys.stdout.write("\n")
        return 0

    print(f"<!-- generated by tools/docker-ros2/render-status.py from the gate's")
    print(f"     own result.json; tree {sha}, measured {date}. Do not hand-edit. -->")
    print()
    print("| ROS 2 distro | Status | Evidence |")
    print("|---|---|---|")
    for row in rows:
        print(f"| {row['distro'].capitalize()} | {row['status']} | {row['detail']} |")
    print()
    print("Reproduce: `scripts/ros2/gate-ros2.sh --distro <distro>`.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
