/// Run a full 3-message PKI-DH handshake between `peer_prefix` and
/// `local_prefix` and return the LOCAL machine, holding a `Complete` session
/// for the peer, keyed the way the wire keys it (the participant entity id).
///
/// Either role: the lower prefix initiates (DDS Security v1.1 Sec.9.3.4), and
/// the peer's permissions document travels in its AuthRequest or its
/// AuthReply, whichever it sends, and lands in the local machine's `Complete`
/// state.
///
/// Shared, not copied: the discovery gate tests and the departure tests both
/// need a peer that authenticated the way the protocol makes it authenticate.
pub(crate) fn local_machine_with_completed_peer(
    local_prefix: [u8; 12],
    peer_prefix: [u8; 12],
    peer_permissions: Option<Vec<u8>>,
) -> std::sync::Arc<crate::security::handshake::HandshakeMachine> {
    local_machine_with_completed_peer_capabilities(
        local_prefix,
        peer_prefix,
        peer_permissions,
        crate::protocol::group::LOCAL_CAPABILITIES,
    )
}

/// Complete a real handshake with the capabilities the peer signs.
pub(crate) fn local_machine_with_completed_peer_capabilities(
    local_prefix: [u8; 12],
    peer_prefix: [u8; 12],
    peer_permissions: Option<Vec<u8>>,
    caps: u32,
) -> std::sync::Arc<crate::security::handshake::HandshakeMachine> {
    use crate::core::discovery::GUID;
    use crate::core::rtps_constants::RTPS_ENTITYID_PARTICIPANT;
    use crate::security::handshake::tokens::{encode_final, encode_reply, encode_request};
    use crate::security::handshake::{HandshakeAction, HandshakeMachine};

    let peer_guid = GUID::new(peer_prefix, RTPS_ENTITYID_PARTICIPANT);
    let local_guid = GUID::new(local_prefix, RTPS_ENTITYID_PARTICIPANT);
    let peer_machine = HandshakeMachine::new()
        .with_local_permissions(peer_permissions)
        .with_local_capabilities_for_tests(caps);
    let local_machine = std::sync::Arc::new(HandshakeMachine::new());
    let cert = TEST_IDENTITY_CERT_PEM.to_vec();
    let key = TEST_IDENTITY_KEY_PEM.to_vec();
    let ca = TEST_CA_CERT_PEM.to_vec();

    // (initiator machine, its guid, responder machine, its guid)
    let (init, init_guid, resp, resp_guid): (&HandshakeMachine, _, &HandshakeMachine, _) =
        if local_prefix < peer_prefix {
            (&local_machine, local_guid, &peer_machine, peer_guid)
        } else {
            (&peer_machine, peer_guid, &local_machine, local_guid)
        };
    let request = match init
        .start(init_guid, resp_guid, &cert, &key)
        .expect("start")
        .expect("the lower prefix is the initiator")
    {
        HandshakeAction::SendRequest(_, token) => encode_request(&token).expect("encode"),
        other => panic!("expected SendRequest, got {:?}", other),
    };
    let reply = match resp
        .on_message(init_guid, &request, resp_guid, &cert, &key, &ca)
        .expect("the request must be accepted")
    {
        HandshakeAction::SendReply(_, token) => encode_reply(&token).expect("encode"),
        other => panic!("expected SendReply, got {:?}", other),
    };
    let final_token = match init
        .on_message(resp_guid, &reply, init_guid, &cert, &key, &ca)
        .expect("the reply must be accepted")
    {
        HandshakeAction::SendFinal(_, token) => encode_final(&token).expect("encode"),
        other => panic!("expected SendFinal, got {:?}", other),
    };
    resp.on_message(init_guid, &final_token, resp_guid, &cert, &key, &ca)
        .expect("the final token must complete the handshake");

    assert!(
        local_machine.is_authenticated(&peer_guid),
        "the fixture handshake must reach Complete or nothing gated on it is under test"
    );
    local_machine
}

/// A handshake between `local_prefix` (the lower prefix, so the initiator)
/// and `peer_prefix` left in progress: the LOCAL machine has sent its
/// request and holds a session that is not complete. The returned closure
/// completes it (the peer's reply reaches the local machine, its final
/// token the peer's).
pub(crate) fn local_machine_with_pending_peer(
    local_prefix: [u8; 12],
    peer_prefix: [u8; 12],
    peer_permissions: Option<Vec<u8>>,
) -> (
    std::sync::Arc<crate::security::handshake::HandshakeMachine>,
    Box<dyn FnOnce() + Send + Sync>,
) {
    use crate::core::discovery::GUID;
    use crate::core::rtps_constants::RTPS_ENTITYID_PARTICIPANT;
    use crate::security::handshake::tokens::{encode_final, encode_reply, encode_request};
    use crate::security::handshake::{HandshakeAction, HandshakeMachine};

    assert!(local_prefix < peer_prefix, "the local machine initiates");
    let peer_guid = GUID::new(peer_prefix, RTPS_ENTITYID_PARTICIPANT);
    let local_guid = GUID::new(local_prefix, RTPS_ENTITYID_PARTICIPANT);
    let peer_machine = HandshakeMachine::new().with_local_permissions(peer_permissions);
    let local_machine = std::sync::Arc::new(HandshakeMachine::new());
    let cert = TEST_IDENTITY_CERT_PEM.to_vec();
    let key = TEST_IDENTITY_KEY_PEM.to_vec();
    let ca = TEST_CA_CERT_PEM.to_vec();
    let request = match local_machine
        .start(local_guid, peer_guid, &cert, &key)
        .expect("start")
        .expect("the lower prefix is the initiator")
    {
        HandshakeAction::SendRequest(_, token) => encode_request(&token).expect("encode"),
        other => panic!("expected SendRequest, got {:?}", other),
    };
    let reply = match peer_machine
        .on_message(local_guid, &request, peer_guid, &cert, &key, &ca)
        .expect("the request must be accepted")
    {
        HandshakeAction::SendReply(_, token) => encode_reply(&token).expect("encode"),
        other => panic!("expected SendReply, got {:?}", other),
    };
    assert!(
        local_machine.has_session(&peer_guid) && !local_machine.is_authenticated(&peer_guid),
        "fixture: in progress"
    );
    let local = std::sync::Arc::clone(&local_machine);
    let finish = Box::new(move || {
        let final_token = match local
            .on_message(peer_guid, &reply, local_guid, &cert, &key, &ca)
            .expect("the reply must be accepted")
        {
            HandshakeAction::SendFinal(_, token) => encode_final(&token).expect("encode"),
            other => panic!("expected SendFinal, got {:?}", other),
        };
        peer_machine
            .on_message(local_guid, &final_token, peer_guid, &cert, &key, &ca)
            .expect("the final token must complete the handshake");
        assert!(local.is_authenticated(&peer_guid), "fixture: complete");
    });
    (local_machine, finish)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_test_prefix_head_is_the_identity_subject_hash() {
        use crate::security::authentication::guid_binding::{
            binding_of, subject_name_der, PrefixBinding,
        };
        let subject = subject_name_der(TEST_IDENTITY_CERT_PEM).expect("subject");
        assert_eq!(
            binding_of(&bound_test_prefix([0; 6]), &subject),
            PrefixBinding::Bound
        );
        let mut off = bound_test_prefix([0; 6]);
        off[5] ^= 0x01;
        assert_eq!(binding_of(&off, &subject), PrefixBinding::Unbound);
        assert!(bound_test_prefix([0x00; 6]) < bound_test_prefix([0xFE; 6]));
    }
}
