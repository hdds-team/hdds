/// The first six octets of every GUID prefix bound to
/// [`TEST_IDENTITY_CERT_PEM`] (DDS-Security 1.1 Sec.9.3.3, Table 52): bit 0
/// set, then the first 47 bits of the SHA-256 of its DER SubjectName
/// (`CN=DDS Test Identity, O=HDDS Test`). Computed outside this crate, with
/// Python's hashlib over the SubjectName cut out of the certificate's DER;
/// `the_test_prefix_head_is_the_identity_subject_hash` pins it against
/// `guid_binding`.
pub(crate) const TEST_IDENTITY_PREFIX_HEAD: [u8; 6] = [0xbe, 0x8b, 0x4f, 0x5e, 0xe2, 0x4e];

/// A participant prefix bound to [`TEST_IDENTITY_CERT_PEM`]:
/// [`TEST_IDENTITY_PREFIX_HEAD`], then `tail` (bits 48 to 95 are free).
/// Two of them compare as their tails do, so a fixture keeps the handshake
/// roles it chose (the lower prefix initiates).
pub(crate) const fn bound_test_prefix(tail: [u8; 6]) -> [u8; 12] {
    let mut prefix = [0u8; 12];
    let mut i = 0;
    while i < 6 {
        prefix[i] = TEST_IDENTITY_PREFIX_HEAD[i];
        prefix[i + 6] = tail[i];
        i += 1;
    }
    prefix
}

