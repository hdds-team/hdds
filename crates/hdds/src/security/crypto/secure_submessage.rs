    /// With an undersized INFO_DST before a valid envelope the ordinary walk
    /// stops, so no ACKNACK may be delivered. RTPS 8.3.4.1: the remainder
    /// after an invalid submessage is rejected.
    ///
    /// `[RTPS header][INFO_DST declaring 4 octets, not the fixed 12 a
    /// GuidPrefix needs][a genuinely valid SEC_PREFIX envelope]`. The
    /// validated walker (`classifier::walk`) stops AT the undersized
    /// INFO_DST and never visits what follows it
    /// (`walk.rs`'s own "the walk ends there" rule for exactly this
    /// shape); `first_secure_prefix` must agree, because it now delegates
    /// to that same walk instead of re-deriving submessage boundaries on
    /// its own.
    ///
    /// Mutant: reverting `first_secure_prefix_from` to its own custom
    /// scan (follow `octetsToNextHeader` without the walker's INFO_DST
    /// validity rule) finds the SEC_PREFIX here regardless, which this test
