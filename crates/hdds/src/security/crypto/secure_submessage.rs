//! DDS-Security 1.1 submessage protection by the builtin
//! DDS:Crypto:AES-GCM-GMAC transformation.
//!
//! `encode_datawriter_submessage` (Sec.8.5.1.9.2, Table 72 of Sec.9.5.3.3.1)
//! protects ONE RTPS submessage. Its wire shape is Sec.9.5.3.3.4.5, in two
//! variants chosen by the key material's transformation kind (Sec.9.5.2.1.1,
//! Table 69):
//!
//! ```text
//! encrypting (AES256_GCM, kind 4)       authenticating only (AES256_GMAC, kind 3)
//! SEC_PREFIX  CryptoHeader              SEC_PREFIX  CryptoHeader
//! SEC_BODY    CryptoContent             <the submessage, unchanged>
//! SEC_POSTFIX CryptoFooter              SEC_POSTFIX CryptoFooter
//! ```
//!
//! SEC_PREFIX is 0x31 (Sec.7.3.7.6), SEC_BODY 0x30 (Sec.7.3.7.5), SEC_POSTFIX
//! 0x32 (Sec.7.3.7.7).
//!
//! - CryptoHeader, big endian whatever the submessage E flag says
//!   (Sec.9.5.2.3): `transformation_kind[4]`, `transformation_key_id[4]`,
//!   `session_id[4]`, `initialization_vector_suffix[8]`.
//! - CryptoContent, big endian (Sec.9.5.2.4): a `long` length N, then the N
//!   octets AES-GCM made of the input submessage. GCM is a counter mode and
//!   adds no padding, so N is the submessage length: the "multiple of 16"
//!   note of Sec.9.5.3.3.4.2 describes a block mode the builtin plugin does
//!   not use. The SEC_BODY body is padded to 4 octets after the N octets
//!   (DDSI-RTPS v2.5 Sec.9.4.1: a submessage starts 4-aligned); the
//!   padding is not part of the CryptoContent.
//! - CryptoFooter, big endian (Sec.9.5.2.5): `common_mac[16]`, then
//!   `receiver_specific_macs`, a sequence of `{receiver_mac_key_id[4],
//!   receiver_mac[16]}`.
//!
//! The common MAC (Sec.9.5.3.3.4.5): encrypting, "the authentication tag
//! generated by the same AES-GCM transformation where the Additional
//! Authenticated Data is empty"; authenticating only, "the authentication
//! tag generated by the AES-GMAC transformation using the SessionKey and the
//! InitializationVector operating on the RTPS Submessage" - AES-GCM with the
//! whole submessage, its header included, as Additional Authenticated Data
//! and nothing to encrypt. Each receiver-specific MAC is "the AES-GMAC tags
//! computed on the common_mac using each of the SessionReceiverSpecificKey
//! and the same InitializationVector": AES-GCM, the 16 octets of the common
//! MAC as AAD.
//!
//! The session key is `HMAC256(MasterKey, "SessionKey" | MasterSalt |
//! SessionId)` and a receiver-specific one `HMAC256(MasterReceiverSpecificKey,
//! "SessionReceiverKey" | MasterSalt | SessionId)` (Sec.9.5.3.3.3); the
//! initialization vector is `SessionId | InitializationVectorSuffix`
//! (Sec.9.5.3.3.4), shared by every key of the sender as that section says.
//! The suffix is a process counter that starts at a random value and never
//! repeats in the process; the session id is drawn at random once per
//! process and incremented when the process has transformed
//! `MAX_BLOCKS_PER_SESSION` blocks under it (Sec.9.5.3.3.4). Every operation
//! takes a suffix no other operation of the process took, so no (key, IV)
//! pair is ever used twice.
//!
//! What this module does NOT decide is where the key material comes from:
//! the caller hands it a [`WriterKeyMaterial`], and a [`ReceiverSpecificKey`]
//! when the protection authenticates the origin. In the specification that
//! material is created by `register_local_datawriter` and
//! `register_matched_datareader` and travels in CryptoTokens (Sec.9.5.3.1,
//! Table 70; Sec.9.5.3.2, Table 71); see `secure_sedp` for where HDDS takes
//! it from today.

#[cfg(feature = "security")]
pub use inner::*;

#[cfg(feature = "security")]
mod inner {
    use crate::security::SecurityError;
    use ring::aead::{Aad, LessSafeKey, Nonce, UnboundKey, AES_256_GCM};
    use ring::hmac;
    use ring::rand::{SecureRandom, SystemRandom};
    use std::sync::atomic::{AtomicU64, Ordering};
    use std::sync::OnceLock;
    use zeroize::{Zeroize, Zeroizing};

    /// SecureBodySubMsg submessage id (DDS-Security 1.1 Sec.7.3.7.5.2).
    pub const SEC_BODY: u8 = 0x30;
    /// SecurePrefixSubMsg submessage id (Sec.7.3.7.6.2).
    pub const SEC_PREFIX: u8 = 0x31;
    /// SecurePostfixSubMsg submessage id (Sec.7.3.7.7.2).
    pub const SEC_POSTFIX: u8 = 0x32;

    /// `CRYPTO_TRANSFORMATION_KIND_AES256_GMAC` (Sec.9.5.2.1.1).
    pub const CRYPTO_TRANSFORMATION_KIND_AES256_GMAC: [u8; 4] = [0, 0, 0, 3];
    /// `CRYPTO_TRANSFORMATION_KIND_AES256_GCM` (Sec.9.5.2.1.1).
    pub const CRYPTO_TRANSFORMATION_KIND_AES256_GCM: [u8; 4] = [0, 0, 0, 4];

    /// CryptoHeader of the builtin plugin: kind 4, key id 4, session id 4,
    /// initialization vector suffix 8 (Sec.9.5.2.3, Sec.9.5.3.3.4.1).
    pub const CRYPTO_HEADER_LEN: usize = 20;
    /// `common_mac` (Sec.9.5.2.5).
    pub const COMMON_MAC_LEN: usize = 16;
    /// One `ReceiverSpecificMAC`: key id 4, MAC 16 (Sec.9.5.2.5).
    const RECEIVER_SPECIFIC_MAC_LEN: usize = 20;
    /// RTPS submessage header: id, flags, octetsToNextHeader.
    const SUBMESSAGE_HEADER_LEN: usize = 4;
    /// RTPS message header (DDSI-RTPS v2.5 Sec.9.4.2): "RTPS" magic,
    /// version, vendor id, 12-octet GUID prefix.
    const RTPS_HEADER_LEN: usize = 20;
    /// The E flag of a submessage header (DDSI-RTPS v2.5 Sec.9.4.5.1.1).
    const FLAG_E: u8 = 0x01;

    /// The two transformations of the builtin plugin this module applies,
    /// both with 256-bit keys (Table 69).
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub enum Transformation {
        /// `AES256_GCM`: encrypt, then MAC (ProtectionKind ENCRYPT).
        Aes256Gcm,
        /// `AES256_GMAC`: MAC only, the submessage left in clear
        /// (ProtectionKind SIGN).
        Aes256Gmac,
    }

    impl Transformation {
        /// The `transformation_kind` octets (Sec.9.5.2.1.1).
        #[must_use]
        pub fn kind(self) -> [u8; 4] {
            match self {
                Self::Aes256Gcm => CRYPTO_TRANSFORMATION_KIND_AES256_GCM,
                Self::Aes256Gmac => CRYPTO_TRANSFORMATION_KIND_AES256_GMAC,
            }
        }

        /// The transformation named by `kind`, if it is one of these two.
        #[must_use]
        pub fn of_kind(kind: [u8; 4]) -> Option<Self> {
            match kind {
                CRYPTO_TRANSFORMATION_KIND_AES256_GCM => Some(Self::Aes256Gcm),
                CRYPTO_TRANSFORMATION_KIND_AES256_GMAC => Some(Self::Aes256Gmac),
                _ => None,
            }
        }
    }

    /// `HMAC256(key, label | master_salt | session_id)` (Sec.9.5.3.3.3).
    fn derive_session_key(
        key: &[u8; 32],
        label: &[u8],
        master_salt: &[u8; 32],
        session_id: [u8; 4],
    ) -> Zeroizing<[u8; 32]> {
        let key = hmac::Key::new(hmac::HMAC_SHA256, key);
        let mut ctx = hmac::Context::with_key(&key);
        ctx.update(label);
        ctx.update(master_salt);
        ctx.update(&session_id);
        let tag = ctx.sign();
        // A session key: wiped by whoever holds it, never returned by value.
        let mut out = Zeroizing::new([0u8; 32]);
        out.copy_from_slice(tag.as_ref());
        out
    }

    /// The master key material of one sending DataWriter, as the builtin
    /// plugin uses it: `transformation_kind`, `master_sender_key`,
    /// `master_salt` and `sender_key_id` of a `KeyMaterial_AES_GCM_GMAC`
    /// (Sec.9.5.2.1.1). The receiver-specific half, when there is one, is a
    /// [`ReceiverSpecificKey`]. Cleared on drop.
    pub struct WriterKeyMaterial {
        transformation: Transformation,
        master_key: [u8; 32],
        master_salt: [u8; 32],
        key_id: [u8; 4],
        /// The SessionIds this material seals under, when they are the
        /// sealer's own rather than the process's (`SealingSession`).
        sealing: Option<std::sync::Arc<SealingSession>>,
    }

    impl WriterKeyMaterial {
        /// Encrypting key material (`AES256_GCM`) from its three parts.
        #[must_use]
        pub fn new(master_key: [u8; 32], master_salt: [u8; 32], key_id: [u8; 4]) -> Self {
            Self {
                transformation: Transformation::Aes256Gcm,
                master_key,
                master_salt,
                key_id,
                sealing: None,
            }
        }

        /// The same material, sealing under `session`'s SessionIds instead
        /// of the process's. Changes nothing in how it opens, nor its
        /// fingerprint.
        #[must_use]
        pub(crate) fn with_sealing_session(
            mut self,
            session: std::sync::Arc<SealingSession>,
        ) -> Self {
            self.sealing = Some(session);
            self
        }

        /// Whether `session_id` is one this material's sealer sealed under
        /// (`SealingSession::sealed_under`): false for a material that seals
        /// under the process's SessionIds.
        #[must_use]
        pub(crate) fn sealed_under(&self, session_id: [u8; 4]) -> bool {
            self.sealing
                .as_ref()
                .is_some_and(|session| session.sealed_under(session_id))
        }

        /// The same material, applying `transformation`.
        #[must_use]
        pub fn with_transformation(mut self, transformation: Transformation) -> Self {
            self.transformation = transformation;
            self
        }

        /// The transformation this material applies.
        #[must_use]
        pub fn transformation(&self) -> Transformation {
            self.transformation
        }

        /// The `transformation_key_id` a CryptoHeader made with this
        /// material carries (Sec.9.5.2.2).
        #[must_use]
        pub fn key_id(&self) -> [u8; 4] {
            self.key_id
        }

        /// A digest identifying this material without revealing it: two
        /// materials have the same fingerprint exactly when they hold the
        /// same transformation, key, salt and key id (up to SHA-256
        /// collisions). For state that must notice the material changed
        /// (a peer that authenticated again) and must not keep the keys.
        #[must_use]
        pub fn fingerprint(&self) -> [u8; 32] {
            let mut ctx = ring::digest::Context::new(&ring::digest::SHA256);
            ctx.update(b"hdds key material fingerprint");
            ctx.update(&self.transformation.kind());
            ctx.update(&self.master_key);
            ctx.update(&self.master_salt);
            ctx.update(&self.key_id);
            let mut out = [0u8; 32];
            out.copy_from_slice(ctx.finish().as_ref());
            out
        }

        /// `SessionKey := HMAC256(MasterKey, "SessionKey" | MasterSalt |
        /// SessionId)` (Sec.9.5.3.3.3).
        pub(crate) fn session_key(&self, session_id: [u8; 4]) -> Zeroizing<[u8; 32]> {
            derive_session_key(
                &self.master_key,
                b"SessionKey",
                &self.master_salt,
                session_id,
            )
        }

        /// `SessionReceiverSpecificKey := HMAC256(MasterReceiverSpecificKey,
        /// "SessionReceiverKey" | MasterSalt | SessionId)` (Sec.9.5.3.3.3):
        /// the sender's salt, the receiver's key.
        fn receiver_session_key(
            &self,
            receiver: &ReceiverSpecificKey,
            session_id: [u8; 4],
        ) -> Zeroizing<[u8; 32]> {
            derive_session_key(
                &receiver.master_key,
                b"SessionReceiverKey",
                &self.master_salt,
                session_id,
            )
        }
    }

    impl Drop for WriterKeyMaterial {
        fn drop(&mut self) {
            self.master_key.zeroize();
            self.master_salt.zeroize();
        }
    }

    impl std::fmt::Debug for WriterKeyMaterial {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.debug_struct("WriterKeyMaterial")
                .field("transformation", &self.transformation)
                .field("key_id", &self.key_id)
                .finish_non_exhaustive()
        }
    }

    /// The receiver-specific half of a `KeyMaterial_AES_GCM_GMAC`:
    /// `receiver_specific_key_id` and `master_receiver_specific_key`
    /// (Sec.9.5.2.1.1), shared by the sender with one receiver only, for the
    /// origin-authenticating protection kinds (Sec.9.4.1.2.2). The key id is
    /// never 0: 0 means "no receiver-specific MAC" (Sec.9.5.2.1.1). Cleared
    /// on drop.
    pub struct ReceiverSpecificKey {
        master_key: [u8; 32],
        key_id: [u8; 4],
    }

    impl ReceiverSpecificKey {
        /// The key and its id; `None` for the id 0, which names no key.
        #[must_use]
        pub fn new(master_key: [u8; 32], key_id: [u8; 4]) -> Option<Self> {
            (key_id != [0; 4]).then_some(Self { master_key, key_id })
        }

        /// `receiver_mac_key_id` of the MAC made with this key.
        #[must_use]
        pub fn key_id(&self) -> [u8; 4] {
            self.key_id
        }
    }

    impl Drop for ReceiverSpecificKey {
        fn drop(&mut self) {
            self.master_key.zeroize();
        }
    }

    impl std::fmt::Debug for ReceiverSpecificKey {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            f.debug_struct("ReceiverSpecificKey")
                .field("key_id", &self.key_id)
                .finish_non_exhaustive()
        }
    }

    /// The most AES blocks one SessionId transforms before the next one is
    /// taken (`max_blocks_per_session`, DDS-Security 1.1 Sec.9.5.3.3.2,
    /// Table 73, and Sec.9.5.3.3.4: "If the operation detects that the
    /// counter would exceed the maximum then it should modify the SessionId
    /// and derive new session keys prior to transforming any of the input
    /// plain text"). The specification leaves the value to configuration;
    /// 2^32 blocks (64 GiB) is the AES-GCM bound NIST SP 800-38D gives per
    /// key for ciphertext volume, counted here across every master key of
    /// the process, so each session key stays under it.
    pub(crate) const MAX_BLOCKS_PER_SESSION: u64 = 1 << 32;

    /// The SessionId of this process and the blocks it has transformed.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub(crate) struct Session {
        pub(crate) id: u32,
        pub(crate) blocks: u64,
    }

    impl Session {
        /// The SessionId under which `plaintext_len` more octets are
        /// transformed: this one, or, when they would take it past
        /// `MAX_BLOCKS_PER_SESSION`, the next (Sec.9.5.3.3.4: the SessionId
        /// is incremented, which derives new session keys and resets the
        /// counter).
        pub(crate) fn take(&mut self, plaintext_len: usize) -> [u8; 4] {
            let blocks = u64::try_from(plaintext_len)
                .unwrap_or(u64::MAX)
                .div_ceil(16);
            if self.blocks.saturating_add(blocks) > MAX_BLOCKS_PER_SESSION {
                self.id = self.id.wrapping_add(1);
                self.blocks = 0;
            }
            self.blocks = self.blocks.saturating_add(blocks);
            self.id.to_be_bytes()
        }
    }

    /// SessionIds of one sealer, apart from the process's: a random first
    /// one, the next taken past `MAX_BLOCKS_PER_SESSION` as the process's
    /// are (`Session::take`).
    ///
    /// For key material both ends of a pair seal with, the volatile
    /// channel's KxKeys (DDS Security v1.1 Sec.9.5.2.1.2, Table 67, one
    /// material for both directions): a submessage a participant sealed,
    /// sent back to it under the peer's prefix, opens, and nothing in it
    /// says which end sealed it. The SessionId does, once each end seals
    /// under its own. The chance that two ends draw overlapping SessionIds
    /// is that of two random 32-bit values meeting.
    #[derive(Debug)]
    pub(crate) struct SealingSession {
        first: u32,
        session: std::sync::Mutex<Session>,
    }

    impl SealingSession {
        /// A new sealer's SessionIds, from a random first one.
        pub(crate) fn new() -> Result<Self, SecurityError> {
            let mut id = [0u8; 4];
            SystemRandom::new().fill(&mut id).map_err(|_| {
                SecurityError::CryptoError(
                    "no randomness for a DDS-Security session id: nothing is sealed".into(),
                )
            })?;
            let first = u32::from_be_bytes(id);
            Ok(Self {
                first,
                session: std::sync::Mutex::new(Session {
                    id: first,
                    blocks: 0,
                }),
            })
        }

        /// The SessionId under which `plaintext_len` more octets are sealed.
        fn take(&self, plaintext_len: usize) -> [u8; 4] {
            self.session
                .lock()
                .unwrap_or_else(|e| e.into_inner())
                .take(plaintext_len)
        }

        /// Whether this sealer took `session_id`: between the first and the
        /// current one, in the order they are taken.
        pub(crate) fn sealed_under(&self, session_id: [u8; 4]) -> bool {
            let current = self.session.lock().unwrap_or_else(|e| e.into_inner()).id;
            u32::from_be_bytes(session_id).wrapping_sub(self.first)
                <= current.wrapping_sub(self.first)
        }
    }

    /// The session id under which `plaintext_len` octets are transformed
    /// now, and the next initialization vector suffix of this process
    /// (module docs). The suffix never repeats in the process, whatever the
    /// session: a key derived for a session id is never used twice with one
    /// IV.
    pub(crate) fn next_initialization_vector(
        plaintext_len: usize,
    ) -> Result<([u8; 4], [u8; 8]), SecurityError> {
        static SESSION: OnceLock<Option<std::sync::Mutex<Session>>> = OnceLock::new();
        let random = |out: &mut [u8]| SystemRandom::new().fill(out).is_ok();
        let session_id = SESSION
            .get_or_init(|| {
                let mut id = [0u8; 4];
                random(&mut id).then(|| {
                    std::sync::Mutex::new(Session {
                        id: u32::from_be_bytes(id),
                        blocks: 0,
                    })
                })
            })
            .as_ref()
            .ok_or_else(|| {
                SecurityError::CryptoError(
                    "no randomness for the DDS-Security session id: nothing is encrypted".into(),
                )
            })?
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .take(plaintext_len);
        Ok((session_id, next_initialization_vector_suffix()?))
    }

    /// The next initialization vector suffix of this process: never the
    /// same twice, whatever the SessionId it goes with.
    fn next_initialization_vector_suffix() -> Result<[u8; 8], SecurityError> {
        static SUFFIX: OnceLock<Option<AtomicU64>> = OnceLock::new();
        let random = |out: &mut [u8]| SystemRandom::new().fill(out).is_ok();
        let suffix = SUFFIX
            .get_or_init(|| {
                let mut start = [0u8; 8];
                random(&mut start).then(|| AtomicU64::new(u64::from_be_bytes(start)))
            })
            .as_ref()
            .ok_or_else(|| {
                SecurityError::CryptoError(
                    "no randomness for the DDS-Security initialization vector: nothing is \
                     encrypted"
                        .into(),
                )
            })?
            .fetch_add(1, Ordering::Relaxed);
        Ok(suffix.to_be_bytes())
    }

    /// An AES-256-GCM key and the nonce `session_id | iv_suffix`.
    pub(crate) fn gcm(
        mut session_key: [u8; 32],
        session_id: [u8; 4],
        iv_suffix: [u8; 8],
    ) -> Result<(LessSafeKey, Nonce), SecurityError> {
        let key = UnboundKey::new(&AES_256_GCM, &session_key);
        session_key.zeroize();
        let key = key.map_err(|_| SecurityError::CryptoError("AES-256-GCM key".into()))?;
        let mut iv = [0u8; 12];
        iv[..4].copy_from_slice(&session_id);
        iv[4..].copy_from_slice(&iv_suffix);
        Ok((LessSafeKey::new(key), Nonce::assume_unique_for_key(iv)))
    }

    /// AES-GMAC of `aad` (AES-GCM, nothing encrypted): the 16-octet tag.
    fn gmac(
        session_key: [u8; 32],
        session_id: [u8; 4],
        iv_suffix: [u8; 8],
        aad: &[u8],
    ) -> Result<[u8; 16], SecurityError> {
        let (key, nonce) = gcm(session_key, session_id, iv_suffix)?;
        let mut empty: [u8; 0] = [];
        let tag = key
            .seal_in_place_separate_tag(nonce, Aad::from(aad), &mut empty)
            .map_err(|_| SecurityError::CryptoError("AES-256-GMAC failed".into()))?;
        let mut out = [0u8; 16];
        out.copy_from_slice(tag.as_ref());
        Ok(out)
    }

    /// Whether `tag` is the AES-GMAC of `aad` (constant time: ring compares).
    fn gmac_verifies(
        session_key: [u8; 32],
        session_id: [u8; 4],
        iv_suffix: [u8; 8],
        aad: &[u8],
        tag: &[u8],
    ) -> bool {
        let Ok((key, nonce)) = gcm(session_key, session_id, iv_suffix) else {
            return false;
        };
        let mut in_out = tag.to_vec();
        key.open_in_place(nonce, Aad::from(aad), &mut in_out)
            .is_ok_and(|plain| plain.is_empty())
    }

    /// One submessage header: id, the E flag, octetsToNextHeader little
    /// endian.
    fn header(id: u8, body_len: usize) -> Result<[u8; 4], SecurityError> {
        let len = u16::try_from(body_len).map_err(|_| {
            SecurityError::CryptoError(format!(
                "a protected submessage of {} octets does not fit octetsToNextHeader",
                body_len
            ))
        })?;
        let [lo, hi] = len.to_le_bytes();
        Ok([id, FLAG_E, lo, hi])
    }

    /// `encode_datawriter_submessage` of the builtin plugin
    /// (Sec.9.5.3.3.4.5): what replaces `submessage`, one complete RTPS
    /// submessage (its header included), under `material`'s
    /// transformation, without receiver-specific MACs.
    pub fn encode_datawriter_submessage(
        material: &WriterKeyMaterial,
        submessage: &[u8],
    ) -> Result<Vec<u8>, SecurityError> {
        encode_datawriter_submessage_for(material, submessage, None)
    }

    /// [`encode_datawriter_submessage`], with the receiver-specific MAC of
    /// `receiver` when given (the WITH_ORIGIN_AUTHENTICATION kinds,
    /// Sec.9.4.1.2.2, Sec.9.5.2.5).
    pub fn encode_datawriter_submessage_for(
        material: &WriterKeyMaterial,
        submessage: &[u8],
        receiver: Option<&ReceiverSpecificKey>,
    ) -> Result<Vec<u8>, SecurityError> {
        let (session_id, iv_suffix) = match &material.sealing {
            Some(sealing) => (
                sealing.take(submessage.len()),
                next_initialization_vector_suffix()?,
            ),
            None => next_initialization_vector(submessage.len())?,
        };
        let session_key = material.session_key(session_id);

        let mut out = Vec::with_capacity(
            3 * SUBMESSAGE_HEADER_LEN
                + CRYPTO_HEADER_LEN
                + 4
                + submessage.len()
                + 3
                + COMMON_MAC_LEN
                + 4
                + RECEIVER_SPECIFIC_MAC_LEN,
        );
        out.extend_from_slice(&header(SEC_PREFIX, CRYPTO_HEADER_LEN)?);
        out.extend_from_slice(&material.transformation.kind());
        out.extend_from_slice(&material.key_id);
        out.extend_from_slice(&session_id);
        out.extend_from_slice(&iv_suffix);

        let common_mac: [u8; 16] = match material.transformation {
            Transformation::Aes256Gcm => {
                let (key, nonce) = gcm(*session_key, session_id, iv_suffix)?;
                let mut ciphertext = submessage.to_vec();
                let tag = key
                    .seal_in_place_separate_tag(nonce, Aad::empty(), &mut ciphertext)
                    .map_err(|_| {
                        SecurityError::CryptoError("AES-256-GCM encryption failed".into())
                    })?;
                let content_len = u32::try_from(ciphertext.len())
                    .map_err(|_| SecurityError::CryptoError("CryptoContent too long".into()))?;
                let body_len = 4 + ciphertext.len();
                let body_padding = (4 - body_len % 4) % 4;
                out.extend_from_slice(&header(SEC_BODY, body_len + body_padding)?);
                out.extend_from_slice(&content_len.to_be_bytes());
                out.extend_from_slice(&ciphertext);
                out.extend(std::iter::repeat_n(0u8, body_padding));
                let mut mac = [0u8; 16];
                mac.copy_from_slice(tag.as_ref());
                mac
            }
            Transformation::Aes256Gmac => {
                // The submessage itself sits between the prefix and the
                // postfix, so its own length must describe it: an
                // octetsToNextHeader of 0 ("to the end of the message")
                // would swallow the SEC_POSTFIX.
                let declared = submessage
                    .get(2..4)
                    .map(|n| {
                        if submessage[1] & FLAG_E != 0 {
                            u16::from_le_bytes([n[0], n[1]])
                        } else {
                            u16::from_be_bytes([n[0], n[1]])
                        }
                    })
                    .ok_or_else(|| {
                        SecurityError::CryptoError("no submessage to authenticate".into())
                    })?;
                if usize::from(declared) + SUBMESSAGE_HEADER_LEN != submessage.len()
                    || !submessage.len().is_multiple_of(4)
                {
                    return Err(SecurityError::CryptoError(
                        "an authenticated submessage must declare its own length and end \
                         4-aligned"
                            .into(),
                    ));
                }
                let mac = gmac(*session_key, session_id, iv_suffix, submessage)?;
                out.extend_from_slice(submessage);
                mac
            }
        };

        let macs = usize::from(receiver.is_some());
        out.extend_from_slice(&header(
            SEC_POSTFIX,
            COMMON_MAC_LEN + 4 + macs * RECEIVER_SPECIFIC_MAC_LEN,
        )?);
        out.extend_from_slice(&common_mac);
        out.extend_from_slice(&u32::from(receiver.is_some()).to_be_bytes());
        if let Some(receiver) = receiver {
            let receiver_key = material.receiver_session_key(receiver, session_id);
            let receiver_mac = gmac(*receiver_key, session_id, iv_suffix, &common_mac)?;
            out.extend_from_slice(&receiver.key_id);
            out.extend_from_slice(&receiver_mac);
        }
        Ok(out)
    }

    /// One submessage of a datagram, as its header describes it.
    struct Submessage {
        id: u8,
        body: std::ops::Range<usize>,
    }

    /// The submessage at `at`, its body bounded by the datagram. `None`
    /// when its header does not fit, or the length it declares runs past
    /// the end. octetsToNextHeader 0 is the last submessage, running to the
    /// end (DDSI-RTPS v2.5 Sec.9.4.5.1.3).
    fn submessage_at(buf: &[u8], at: usize) -> Option<Submessage> {
        let head = buf.get(at..at + SUBMESSAGE_HEADER_LEN)?;
        let declared = if head[1] & FLAG_E != 0 {
            u16::from_le_bytes([head[2], head[3]])
        } else {
            u16::from_be_bytes([head[2], head[3]])
        };
        let start = at + SUBMESSAGE_HEADER_LEN;
        let end = if declared == 0 {
            buf.len()
        } else {
            start + usize::from(declared)
        };
        (end <= buf.len()).then_some(Submessage {
            id: head[0],
            body: start..end,
        })
    }

    /// What [`decode_datawriter_submessage`] recovered: the submessage the
    /// writer protected, and where the SEC_POSTFIX that closed it ends.
    #[derive(Debug)]
    pub struct Decoded {
        /// The protected submessage, header included, as the writer built it.
        pub submessage: Vec<u8>,
        /// One past the SEC_POSTFIX.
        pub end: usize,
        /// The transformation it was protected with.
        pub transformation: Transformation,
        /// Whether a receiver-specific MAC under the key given to the decode
        /// verified (always false when none was given).
        pub origin_authenticated: bool,
        /// The SessionId of its CryptoHeader (Sec.9.5.2.2).
        pub session_id: [u8; 4],
    }

    /// Why a protected submessage was not decoded.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum DecodeRefusal {
        /// The three submessages are not a SEC_PREFIX, a SEC_BODY or a
        /// clear submessage, and a SEC_POSTFIX whose elements fit them
        /// (Sec.7.3.6.3.3, 7.3.6.4.3, 7.3.6.5.3).
        Malformed,
        /// A transformation kind other than the one the key material names.
        UnknownTransformation,
        /// A `transformation_key_id` this key material is not: the sender
        /// used key material the receiver does not hold (Sec.9.5.3.3.1,
        /// `preprocess_secure_submsg`).
        KeyNotHeld,
        /// The common MAC does not verify.
        NotAuthentic,
        /// A receiver-specific key was given and no MAC under it verifies.
        NotOriginAuthentic,
        /// It verifies, and what it protects is not one RTPS submessage.
        NotASubmessage,
    }

    /// The transformation the CryptoHeader of the SEC_PREFIX at
    /// `prefix_at` names, before anything is verified: what key material
    /// to decode it with. `None` when there is no such header, or it names
    /// a transformation this module does not apply.
    #[must_use]
    pub fn transformation_at(buf: &[u8], prefix_at: usize) -> Option<Transformation> {
        let prefix = submessage_at(buf, prefix_at)?;
        if prefix.id != SEC_PREFIX || prefix.body.len() < CRYPTO_HEADER_LEN {
            return None;
        }
        let kind: [u8; 4] = buf
            .get(prefix.body.start..prefix.body.start + 4)?
            .try_into()
            .ok()?;
        Transformation::of_kind(kind)
    }

    /// `decode_datawriter_submessage` (Sec.9.5.3.3.1, Table 72) of the
    /// protected submessage whose SEC_PREFIX is at `prefix_at` in `buf`,
    /// receiver-specific MACs not checked.
    pub fn decode_datawriter_submessage(
        material: &WriterKeyMaterial,
        buf: &[u8],
        prefix_at: usize,
    ) -> Result<Decoded, DecodeRefusal> {
        decode_datawriter_submessage_for(material, buf, prefix_at, None)
    }

    /// [`decode_datawriter_submessage`], requiring, when `receiver` is
    /// given, a receiver-specific MAC under that key that verifies.
    pub fn decode_datawriter_submessage_for(
        material: &WriterKeyMaterial,
        buf: &[u8],
        prefix_at: usize,
        receiver: Option<&ReceiverSpecificKey>,
    ) -> Result<Decoded, DecodeRefusal> {
        let prefix = submessage_at(buf, prefix_at).ok_or(DecodeRefusal::Malformed)?;
        if prefix.id != SEC_PREFIX || prefix.body.len() < CRYPTO_HEADER_LEN {
            return Err(DecodeRefusal::Malformed);
        }
        let crypto_header = &buf[prefix.body.start..prefix.body.start + CRYPTO_HEADER_LEN];
        if crypto_header[0..4] != material.transformation.kind() {
            return Err(DecodeRefusal::UnknownTransformation);
        }
        if crypto_header[4..8] != material.key_id {
            return Err(DecodeRefusal::KeyNotHeld);
        }
        let session_id: [u8; 4] = crypto_header[8..12]
            .try_into()
            .map_err(|_| DecodeRefusal::Malformed)?;
        let iv_suffix: [u8; 8] = crypto_header[12..20]
            .try_into()
            .map_err(|_| DecodeRefusal::Malformed)?;

        // The middle submessage: a SEC_BODY when encrypted, the protected
        // submessage itself, in clear, when only authenticated.
        let body = submessage_at(buf, prefix.body.end).ok_or(DecodeRefusal::Malformed)?;
        let middle_is_body = body.id == SEC_BODY;
        if middle_is_body != (material.transformation == Transformation::Aes256Gcm)
            || matches!(body.id, SEC_PREFIX | SEC_POSTFIX)
        {
            return Err(DecodeRefusal::Malformed);
        }
        let postfix = submessage_at(buf, body.body.end).ok_or(DecodeRefusal::Malformed)?;
        if postfix.id != SEC_POSTFIX || postfix.body.len() < COMMON_MAC_LEN + 4 {
            return Err(DecodeRefusal::Malformed);
        }

        let footer = &buf[postfix.body.clone()];
        let common_mac = &footer[..COMMON_MAC_LEN];
        let macs = u32::from_be_bytes([
            footer[COMMON_MAC_LEN],
            footer[COMMON_MAC_LEN + 1],
            footer[COMMON_MAC_LEN + 2],
            footer[COMMON_MAC_LEN + 3],
        ]);
        let macs = usize::try_from(macs).map_err(|_| DecodeRefusal::Malformed)?;
        let macs_len = macs
            .checked_mul(RECEIVER_SPECIFIC_MAC_LEN)
            .ok_or(DecodeRefusal::Malformed)?;
        if COMMON_MAC_LEN + 4 + macs_len > footer.len() {
            return Err(DecodeRefusal::Malformed);
        }

        let session_key = material.session_key(session_id);
        let plain = match material.transformation {
            Transformation::Aes256Gcm => {
                let content = &buf[body.body.clone()];
                let declared = content
                    .get(0..4)
                    .map(|n| u32::from_be_bytes([n[0], n[1], n[2], n[3]]))
                    .ok_or(DecodeRefusal::Malformed)?;
                let declared = usize::try_from(declared).map_err(|_| DecodeRefusal::Malformed)?;
                let ciphertext = content
                    .get(4..4usize.saturating_add(declared))
                    .ok_or(DecodeRefusal::Malformed)?;
                let (key, nonce) = gcm(*session_key, session_id, iv_suffix)
                    .map_err(|_| DecodeRefusal::NotAuthentic)?;
                let mut in_out = Vec::with_capacity(ciphertext.len() + COMMON_MAC_LEN);
                in_out.extend_from_slice(ciphertext);
                in_out.extend_from_slice(common_mac);
                let plain_len = key
                    .open_in_place(nonce, Aad::empty(), &mut in_out)
                    .map_err(|_| DecodeRefusal::NotAuthentic)?
                    .len();
                in_out.truncate(plain_len);
                in_out
            }
            Transformation::Aes256Gmac => {
                // The submessage, header included, as it was authenticated.
                let clear = &buf[prefix.body.end..body.body.end];
                if !gmac_verifies(*session_key, session_id, iv_suffix, clear, common_mac) {
                    return Err(DecodeRefusal::NotAuthentic);
                }
                clear.to_vec()
            }
        };

        // "the returned RTPS SubMessage shall match the input to the
        // encode_datawriter_message operation" (Table 72): one submessage,
        // exactly, whose header describes the octets that follow it.
        match submessage_at(&plain, 0) {
            Some(inner) if inner.body.end == plain.len() => {}
            _ => return Err(DecodeRefusal::NotASubmessage),
        }

        // Receiver-specific MACs: the one under our key, when we hold one.
        let origin_authenticated = match receiver {
            None => false,
            Some(receiver) => {
                let receiver_key = material.receiver_session_key(receiver, session_id);
                let ok = footer[COMMON_MAC_LEN + 4..COMMON_MAC_LEN + 4 + macs_len]
                    .chunks_exact(RECEIVER_SPECIFIC_MAC_LEN)
                    .filter(|mac| mac[..4] == receiver.key_id)
                    .any(|mac| {
                        gmac_verifies(*receiver_key, session_id, iv_suffix, common_mac, &mac[4..])
                    });
                if !ok {
                    return Err(DecodeRefusal::NotOriginAuthentic);
                }
                true
            }
        };

        Ok(Decoded {
            submessage: plain,
            end: postfix.body.end,
            transformation: material.transformation,
            origin_authenticated,
            session_id,
        })
    }

    /// `encode_datareader_submessage` of the builtin plugin (Sec.8.5.1.9.3,
    /// Table 72 of Sec.9.5.3.3.1): what replaces `submessage`, one complete
    /// RTPS submessage (its header included) built by a DataReader -- an
    /// ACKNACK or a NACK_FRAG (Sec.8.8.9.3) -- under `material`'s
    /// transformation, without receiver-specific MACs.
    ///
    /// Table 72 gives `encode_datawriter_submessage` and
    /// `encode_datareader_submessage` as two distinct operations because a
    /// writer and a reader protect different submessages, not because the
    /// transform itself differs: Sec.9.5.3.3.4.5's wire shape (SEC_PREFIX
    /// CryptoHeader, the encrypted or authenticated submessage, SEC_POSTFIX
    /// CryptoFooter) and the session-key derivation of Sec.9.5.3.3.3 read
    /// the same for both directions, keyed only by whatever
    /// [`WriterKeyMaterial`] the caller passes -- a writer's key material
    /// when a writer calls this, a reader's when a reader does. This is
    /// that same transform under the reader-facing name, so a reader's
    /// ACKNACK/NACK_FRAG protection and a writer's DATA/HEARTBEAT/GAP
    /// protection are provably the one mechanism, not two that happen to
    /// agree.
    pub fn encode_datareader_submessage(
        material: &WriterKeyMaterial,
        submessage: &[u8],
    ) -> Result<Vec<u8>, SecurityError> {
        encode_datawriter_submessage_for(material, submessage, None)
    }

    /// [`encode_datareader_submessage`], with the receiver-specific MAC of
    /// `receiver` when given (the WITH_ORIGIN_AUTHENTICATION kinds,
    /// Sec.9.4.1.2.2, Sec.9.5.2.5) -- the reader-facing name of
    /// [`encode_datawriter_submessage_for`], same reason as above.
    pub fn encode_datareader_submessage_for(
        material: &WriterKeyMaterial,
        submessage: &[u8],
        receiver: Option<&ReceiverSpecificKey>,
    ) -> Result<Vec<u8>, SecurityError> {
        encode_datawriter_submessage_for(material, submessage, receiver)
    }

    /// `decode_datareader_submessage` (Sec.9.5.3.3.1, Table 72) of a
    /// protected submessage built by a DataReader -- an ACKNACK or a
    /// NACK_FRAG -- whose SEC_PREFIX is at `prefix_at` in `buf`,
    /// receiver-specific MACs not checked. The reader-facing name of
    /// [`decode_datawriter_submessage`]; see that function's sibling
    /// [`encode_datareader_submessage`] for why sharing the transform is
    /// correct, not a shortcut.
    pub fn decode_datareader_submessage(
        material: &WriterKeyMaterial,
        buf: &[u8],
        prefix_at: usize,
    ) -> Result<Decoded, DecodeRefusal> {
        decode_datawriter_submessage_for(material, buf, prefix_at, None)
    }

    /// [`decode_datareader_submessage`], requiring, when `receiver` is
    /// given, a receiver-specific MAC under that key that verifies.
    pub fn decode_datareader_submessage_for(
        material: &WriterKeyMaterial,
        buf: &[u8],
        prefix_at: usize,
        receiver: Option<&ReceiverSpecificKey>,
    ) -> Result<Decoded, DecodeRefusal> {
        decode_datawriter_submessage_for(material, buf, prefix_at, receiver)
    }

    /// Where the first SEC_PREFIX of an RTPS message is. `None` when there
    /// is none, or the VALIDATED walk
    /// (`classifier::walk::for_each_submessage`) stops before reaching one.
    ///
    /// This scanner delegates to the validated walk every other consumer of
    /// the datagram follows, rather than walking the submessage chain with
    /// its OWN minimal header check (declared length only). An undersized INFO_DST (or
    /// INFO_TS, INFO_SRC, INFO_REPLY) ahead of a perfectly valid SEC_PREFIX
    /// makes the REST OF THE MESSAGE invalid (DDSI-RTPS v2.5 Sec.8.3.4.1
    /// rule 6: a known submessage too short for its own contents
    /// invalidates everything behind it, because reading past it would
    /// borrow bytes from whatever follows). The validated walker already
    /// enforces that by simply never visiting anything after such a
    /// submessage; delegating to it here means this scanner cannot
    /// report a SEC_PREFIX the rest of the receiver pipeline would refuse
    /// to have reached. It also inherits the walker's PAD/INFO_TS
    /// zero-length rule (Sec.9.4.5.1.3: `octetsToNextHeader == 0` means
    /// "last, runs to the end" for every OTHER kind, but an EMPTY body
    /// right before the next header for PAD and INFO_TS specifically).
    #[must_use]
    pub fn first_secure_prefix(datagram: &[u8]) -> Option<usize> {
        first_secure_prefix_from(datagram, RTPS_HEADER_LEN)
    }

    /// [`first_secure_prefix`], reporting only a SEC_PREFIX at or after
    /// `start`: finds a SECOND (or later) SEC_PREFIX of a compound
    /// datagram once the caller knows where the first envelope ended
    /// (DDS-Security v1.1 does not forbid several independently-protected
    /// control submessages in one RTPS message, e.g. a secure SEDP
    /// publications ACKNACK and a subscriptions one, possibly separated by
    /// an INFO_TS). The walk still runs from the very start of the
    /// datagram's submessages -- receiver state (INFO_DST/INFO_TS/
    /// INFO_SRC) is cumulative, so a validity failure before `start` must
    /// still suppress anything after it, exactly as it would for the
    /// first SEC_PREFIX.
    ///
    /// PERFORMANCE: a caller
    /// that finds envelope after envelope by repeatedly advancing `start`
    /// (`DiscoveryDispatch::handle_secure_sedp`'s own loop) re-walks from
    /// offset 20 every time, so a datagram of N independently-protected
    /// envelopes costs O(N^2) submessage visits rather than O(N) -- bounded
    /// by one UDP datagram's submessage count (a few dozen at most in any
    /// shape this crate builds or has seen on the wire), not a DoS surface,
    /// but real repeated work. A single-traversal fix needs one of: the
    /// shared walker (`classifier::walk::for_each_submessage`) gaining a
    /// "resume from a known-good offset with its receiver state already
    /// reconstructed" entry point, which does not exist today and is not a
    /// change to make to a walker every other scanner in the crate also
    /// depends on; or this function's
    /// callers switching to a "collect every valid SEC_PREFIX in one pass"
    /// query instead of one "find the next one" call per envelope. Neither is
    /// done today.
    #[must_use]
    pub fn first_secure_prefix_from(datagram: &[u8], start: usize) -> Option<usize> {
        use crate::core::discovery::multicast::classifier::walk::{for_each_submessage, Step};
        let mut found = None;
        for_each_submessage(datagram, |sub| {
            if sub.offset >= start && sub.id == SEC_PREFIX {
                found = Some(sub.offset);
                return Step::Stop;
            }
            Step::Continue
        });
        found
    }
}

