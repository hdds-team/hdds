//! The one thing DNS-SD needs from `/etc/resolv.conf`: the nameserver list.
//!
//! Only `nameserver` lines are read. `search`, `domain`, `options` and
//! everything else are deliberately ignored: DNS-SD asks for one fully
//! qualified name built from the configured service and zone, so a search
//! list would only add ways for the query to mean something else.
//!
//! A malformed or unreadable file yields an empty list, never an error and
//! never a panic; the caller decides what an empty list means (the
//! participant builder refuses to start DNS-SD with no nameserver, rather
//! than silently querying nothing).

use std::net::{IpAddr, SocketAddr};
use std::path::Path;

/// Default DNS service port.
pub const DNS_PORT: u16 = 53;

/// The file a Unix host keeps its resolver configuration in.
pub const RESOLV_CONF_PATH: &str = "/etc/resolv.conf";

/// Nameservers from the host's `/etc/resolv.conf`, empty when it cannot
/// be read or lists none.
pub fn system_nameservers() -> Vec<SocketAddr> {
    nameservers_from_file(RESOLV_CONF_PATH)
}

/// Nameservers from a specific file (the unit tests' entry point).
pub fn nameservers_from_file(path: impl AsRef<Path>) -> Vec<SocketAddr> {
    match std::fs::read_to_string(path.as_ref()) {
        Ok(text) => parse_nameservers(&text),
        Err(error) => {
            log::debug!(
                "[DNS-SD] Cannot read {}: {}",
                path.as_ref().display(),
                error
            );
            Vec::new()
        }
    }
}

/// Parse the `nameserver` lines of a `resolv.conf` body.
///
/// Accepts an IPv4 or IPv6 literal, with an optional `%zone` suffix
/// (dropped: the std parser has no scope-id support and a link-local
/// resolver is not a DNS-SD deployment). Duplicates are collapsed, order
/// is preserved, and anything unparsable is skipped with a debug log.
pub fn parse_nameservers(text: &str) -> Vec<SocketAddr> {
    let mut out: Vec<SocketAddr> = Vec::new();
    for raw in text.lines() {
        // A comment starts with '#' or ';' and runs to the end of line.
        let line = raw.split(['#', ';']).next().unwrap_or("").trim();
        let mut fields = line.split_whitespace();
        if fields.next() != Some("nameserver") {
            continue;
        }
        let Some(address) = fields.next() else {
            continue;
        };
        let literal = address.split('%').next().unwrap_or(address);
        match literal.parse::<IpAddr>() {
            Ok(ip) => {
                let addr = SocketAddr::new(ip, DNS_PORT);
                if !out.contains(&addr) {
                    out.push(addr);
                }
            }
            Err(_) => {
                log::debug!(
                    "[DNS-SD] Ignoring unparsable nameserver line: {}",
                    raw.trim()
                );
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_nameserver_lines_and_ignores_everything_else() {
        let text = "\
# generated by something
domain example.test
search example.test corp.example.test
nameserver 192.0.2.53
nameserver   198.51.100.53   # the secondary
nameserver 2001:db8::53
nameserver fe80::1%eth0
nameserver 192.0.2.53
nameserver not-an-address
nameserver
options ndots:5 timeout:1
; nameserver 203.0.113.53
sortlist 192.0.2.0/24
";
        let servers = parse_nameservers(text);
        assert_eq!(
            servers,
            vec![
                "192.0.2.53:53".parse::<SocketAddr>().unwrap(),
                "198.51.100.53:53".parse::<SocketAddr>().unwrap(),
                "[2001:db8::53]:53".parse::<SocketAddr>().unwrap(),
                "[fe80::1]:53".parse::<SocketAddr>().unwrap(),
            ],
            "only nameserver lines, in order, deduplicated, comments stripped"
        );
    }

    #[test]
    fn an_empty_or_missing_file_yields_no_nameserver() {
        assert!(parse_nameservers("").is_empty());
        assert!(parse_nameservers("search example.test\noptions edns0\n").is_empty());
        assert!(nameservers_from_file("/nonexistent/hdds/resolv.conf").is_empty());
    }
}
