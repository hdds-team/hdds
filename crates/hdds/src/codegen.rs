//! Compatibility contract between `hddsgen`-generated Rust code and this
//! `hdds` crate release.
//!
//! `hddsgen` (the IDL generator from the separate hdds_gen repository) compiles IDL into Rust
//! that calls straight into `hdds` internals: the [`dds::DDS`](crate::dds::DDS)
//! trait (`nested_type_objects`, `write_key_holder`, `encodes_xcdr1_natively`,
//! ...), `crate::core`'s `key_hash` helpers, and `crate::xtypes` `TypeObject`
//! shapes such as `PlainSequenceSElemDefn`, `CompleteAliasBody`,
//! `CompleteEnumeratedType`. None of that is part of the crate's stable
//! public API: it changes whenever the generated code's assumptions about
//! those internals change.
//!
//! Before this module existed, generating with a new `hddsgen` and building
//! against an older `hdds` runtime (or the reverse) produced thousands of
//! unrelated-looking compiler errors -- missing trait methods, missing
//! fields, missing types -- with nothing pointing at "upgrade `hdds`" as the
//! fix. [`CODEGEN_ABI`] exists so that mismatch fails with ONE error that
//! names the required runtime version, emitted once per generated file (see
//! the Rust backend in `hdds_gen`).
//!
//! # How the guard works
//!
//! Every file `hddsgen` generates carries a small `const` block like:
//!
//! ```ignore
//! const _: () = assert!(
//!     hdds::codegen::CODEGEN_ABI >= 1,
//!     "this code was generated by hddsgen for hdds::codegen::CODEGEN_ABI >= 1 \
//!      (hdds >= 1.5.0); upgrade the `hdds` crate dependency",
//! );
//! ```
//!
//! On a runtime that satisfies the requirement, the assert is evaluated at
//! compile time and optimized away: zero runtime cost.
//!
//! On a runtime whose `CODEGEN_ABI` is lower, the assert fails at compile
//! time with the message above, naming the exact fix.
//!
//! On a runtime that predates this module entirely (anything before 1.5.0,
//! including the 1.1.3 series), `hdds::codegen` does not exist. rustc reports
//! the generated file's unresolved `use hdds::...` imports first, so the guard
//! is not the first error a user sees, and the guard adds only `could not find
//! codegen in hdds` to that list. Neither error names the fix: the version the
//! `--example` Cargo.toml requests (hdds 1.5.0) is what keeps a stale runtime out.
//!
//! # Bumping this for a future incompatible change
//!
//! 1. Increment [`CODEGEN_ABI`] here.
//! 2. Update the Rust backend in `hdds_gen` (`src/codegen/rust_backend/mod.rs`)
//!    to emit the new required number in its `assert!` and its message.
//! 3. Regenerate the golden/snapshot fixtures.
//!
//! No new symbol name is needed for a numeric bump: the `assert!` message
//! already carries the concrete numbers and the fix. `CODEGEN_ABI` compared
//! with `>=` is deliberately the whole mechanism going forward --
//! [`REQUIRES_HDDS_1_5`] is a one-time, human-readable landmark for the
//! 1.1.3 -> 1.5.0 jump that this module was introduced to fix, not a pattern
//! to repeat per release.

/// ABI contract number for the `hddsgen` <-> `hdds` internals described at
/// the module level. Bump this (never reset it) whenever a change to
/// `dds::DDS`, the CDR2 (`core::ser`) traits, an `xtypes` `TypeObject` shape,
/// or the `KeyHolder` contract would make code generated against the old
/// shape silently wrong, rather than just fail to compile, if left as-is.
///
/// Do NOT bump this for additions that stay backward compatible with
/// existing generated code (new optional trait methods with a default body,
/// new enum variants additively encoded, etc).
///
/// `hddsgen` reads this indirectly: it does not call the constant at
/// generation time (it has no way to inspect the `hdds` version it will
/// later be built against), it emits a `const` assertion that the *consuming*
/// build checks this value with `>=` against the number `hddsgen` required
/// when it generated the file.
pub const CODEGEN_ABI: u32 = 1;

/// Named landmark for the 1.1.3 -> 1.5.0 jump. It is a name to grep for, not
/// an error message: on a release that predates `codegen` the compiler reports
/// `could not find \`codegen\` in \`hdds\`` and never reports this
/// symbol's name, so the fix has to come from the version the generated
/// Cargo.toml requests.
///
/// Value equal to [`CODEGEN_ABI`] at the time this constant was introduced;
/// future ABI bumps are tracked by `CODEGEN_ABI` alone (see the module docs),
/// this constant is not renamed per release.
pub const REQUIRES_HDDS_1_5: u32 = CODEGEN_ABI;

// Checked at compile time, so a wrong bump fails every build, not only the
// test run. A zero ABI would make `>= 0` in generated code vacuously true for
// every runtime, silently defeating the guard; the landmark must name the
// same ABI the assert in generated code compares against.
const _: () = assert!(CODEGEN_ABI > 0);
const _: () = assert!(REQUIRES_HDDS_1_5 == CODEGEN_ABI);
